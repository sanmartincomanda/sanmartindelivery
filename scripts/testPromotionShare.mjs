import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { promotionSharePages, promotionShareExpired, promotionShareFilename, promotionShareMoney, renderPromotionShare } from '../src/components/storefront/promotionShare.js';

const products = Array.from({ length: 11 }, (_, i) => ({ code: String(i), name: `Producto ${i}`, price: 100 + i }));
const pages = promotionSharePages(products);
assert.deepEqual(pages.map(page => page.length), [4, 4, 3]);
assert.deepEqual(pages.flat(), products, 'No promotion products may be dropped');
assert.deepEqual(promotionSharePages([]), []);
assert.equal(promotionSharePages([...products, products[0], { code: 'bad', price: 'no' }, null]).flat().length, 11);
assert.equal(promotionSharePages([{ code: 'free', price: 0 }]).flat().length, 1);
assert.deepEqual(promotionSharePages([{ code: 'missing', price: null }, { code: 'blank', price: '' }]), []);
assert.equal(promotionShareExpired('2026-10-20T06:00:00Z', Date.parse('2026-10-20T06:00:00Z')), true);
assert.equal(promotionShareExpired('2026-10-21T06:00:00Z', Date.parse('2026-10-20T06:00:00Z')), false);
assert.equal(promotionShareExpired(''), false);
assert.equal(promotionShareFilename('Promoción / Res', 1), 'san-martin-promocion-res-2.png');
assert.equal(promotionShareMoney(1234.5), 'C$1,234.50');
await assert.rejects(renderPromotionShare({ products: [] }), /No hay productos/);
await assert.rejects(renderPromotionShare({ products, endsAt: '2000-01-01' }), /No hay productos/);
await assert.rejects(renderPromotionShare({ products: [products[0]], endsAt: '2000-01-01' }), /finalizó/);
const component = readFileSync(new URL('../src/components/storefront/PromotionShareButton.jsx', import.meta.url), 'utf8');
assert.match(component, /navigator\.canShare/);
assert.match(component, /cause\.name !== 'AbortError'/);
assert.match(component, /URL\.revokeObjectURL/);
assert.match(component, /aria-modal="true"/);
assert.match(component, /useRetailFocusLayers/);
const store = readFileSync(new URL('../src/components/TiendaVirtualView.jsx', import.meta.url), 'utf8');
assert.match(store, /showAllPromotionProducts && \(\s*<PromotionShareButton/);
assert.match(store, /endsAt: promotion\.endsAt/);
console.log('Promotion share: pagination, deduplication, amounts, expiry, public integration and accessible sheet checks passed.');
